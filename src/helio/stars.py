"""Reference-star heliocentric longitudes, and the coordinate-system
rotation that puts a chosen star at 0 deg Aries.

Data source note (see also README.md): the spec's original plan was to
source all star astrometry from Gaia DR3. In practice **Gaia has little
or no usable astrometry for naked-eye-bright stars** (Regulus, Sirius,
Vega, etc.) -- Gaia's detectors saturate above roughly magnitude 3, and
a live query for Regulus against `gaiadr3.gaia_source` returns nothing
anywhere near its actual brightness. The standard, well-established
alternative for exactly this class of star is the **Hipparcos catalog**
(ESA; using the van Leeuwen 2007 re-reduction, Vizier table
`I/311/hip2`), which was purpose-built to measure bright stars
precisely. Gaia DR3 remains the better choice for fainter reference
points if/when this app adds any (deep-sky objects, faint catalog
stars) -- pick per-object based on what actually has data, not
dogmatically by catalog.

Unlike the live-queried minor bodies, star astrometry (position,
proper motion, parallax at a reference epoch) is static data, so it's
embedded directly below rather than fetched on every call -- this also
means star positions work fully offline. Each entry's source/epoch is
recorded so it can be checked or re-derived later.
"""
