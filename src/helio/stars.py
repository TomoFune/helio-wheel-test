# GCS reference-point groups: each maps to a "center" heliocentric
# longitude computed as the circular mean of its member stars' own
# longitudes (see `group_center_longitude`), not a separately-measured
# object. `dubhe` (already above, part of the 88-constellation set) is
# the Big Dipper's 8th traditional member star, so it's included here
# even though its own catalog entry predates this GCS expansion.
STAR_GROUPS: dict[str, dict] = {
    "orion_belt": {
        "label_ja": "オリオン三ツ星(中央)",
        "name_en": "Orion's Belt (center)",
        "source": "computed: circular mean of mintaka/alnilam/alnitak longitudes",
        "members": ["mintaka", "alnilam", "alnitak"],
    },
    "big_dipper": {
        "label_ja": "北斗七星(中央)",
        "name_en": "Big Dipper (center)",
        "source": "computed: circular mean of dubhe/merak/phecda/megrez/alioth/mizar/alkaid longitudes",
        "members": ["dubhe", "merak", "phecda", "megrez", "alioth", "mizar", "alkaid"],
    },
}


def _star_coord_at_epoch(key: str) -> SkyCoord:
    star = STARS[key]
    return SkyCoord(
        ra=star["ra_deg"] * u.deg,
        dec=star["dec_deg"] * u.deg,
        distance=Distance(parallax=star["parallax_mas"] * u.mas),
        pm_ra_cosdec=star["pm_ra_cosdec_mas_yr"] * u.mas / u.yr,
        pm_dec=star["pm_dec_mas_yr"] * u.mas / u.yr,
        radial_velocity=star["radial_velocity_km_s"] * u.km / u.s,
        obstime=HIPPARCOS_EPOCH,
        frame="icrs",
    )


def star_heliocentric_longitude(key: str, t: Time) -> float:
    """Heliocentric mean-ecliptic-of-date longitude of a reference star,
    with its proper motion propagated from the catalog epoch to `t`."""
    coord_at_epoch = _star_coord_at_epoch(key)
    coord_at_t = coord_at_epoch.apply_space_motion(new_obstime=t)
    result = coord_at_t.transform_to(HeliocentricMeanEcliptic(equinox=t, obstime=t))
    return float(result.lon.to(u.deg).value % 360.0)


def group_center_longitude(group_key: str, t: Time) -> float:
    """Circular mean of a STAR_GROUPS member set's heliocentric
    longitudes at `t` -- e.g. the midpoint of Orion's belt or the Big
    Dipper, used as its own selectable reference point alongside the
    individual member stars. A plain arithmetic mean of longitudes
    breaks down/wraps incorrectly near the 0/360 boundary; averaging
    each member's position as a unit vector on the circle and
    converting back to an angle avoids that."""
    import math

    members = STAR_GROUPS[group_key]["members"]
    lons = [star_heliocentric_longitude(m, t) for m in members]
    x = sum(math.cos(math.radians(lon)) for lon in lons) / len(lons)
    y = sum(math.sin(math.radians(lon)) for lon in lons) / len(lons)
    return math.degrees(math.atan2(y, x)) % 360.0


def rotate_to_reference(body_longitude: float, reference_longitude: float) -> float:
    """(body - reference) mod 360 -- puts the reference point at 0 deg Aries."""
    return (body_longitude - reference_longitude) % 360.0


def search_stars(query: str) -> list[str]:
    """Case-insensitive substring search over Japanese name, English
    name, and constellation (spec section 11: e.g. "Regulus", "レグルス",
    "しし座" should all find the same star)."""
    q = query.strip().lower()
    if not q:
        return []
    return [
        key
        for key, star in STARS.items()
        if q in star["label_ja"].lower()
        or q in star["name_en"].lower()
        or q in star["constellation_ja"].lower()
    ]


def stars_by_constellation() -> dict[str, list[str]]:
    """{constellation_ja: [star_key, ...]} for a constellation-first
    browsing UI (spec section 11)."""
    grouped: dict[str, list[str]] = {}
    for key, star in STARS.items():
        grouped.setdefault(star["constellation_ja"], []).append(key)
    return grouped
